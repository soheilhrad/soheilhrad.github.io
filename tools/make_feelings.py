#!/usr/bin/env python3
"""Place the 16 feelings on the valence-arousal map from published word norms.

Writes _data/feelings.yml, which feeds both the map on the home page and the "Where each feeling
sits" table on the project page. Run it again if the choice of words below changes.

Source of the numbers: Warriner, A. B., Kuperman, V., & Brysbaert, M. (2013). Norms of valence,
arousal, and dominance for 13,915 English lemmas. Behavior Research Methods, 45(4), 1191-1207.
doi:10.3758/s13428-012-0314-x. About 20 raters per word rated valence (1 unpleasant to 9 pleasant)
and arousal (1 calm to 9 excited). The norms file is not part of this repository: download it from
the paper's electronic supplementary material and put it in tools/_raw/ (not committed). Only the
few rows used below are copied into _data/feelings.yml.

Conversion to the map: (rating - 5) / 4, so 1..9 becomes -1..+1 and 5 is the centre. Nothing is
stretched or re-centred, so the dots sit where the raters put them (word ratings bunch near the
middle of the arousal scale, so no feeling reaches the top of the map).

Each feeling gets one of three statuses:
  published   the feeling's own word was rated
  related     a form of the word was rated (transcendent for transcendence, playful for playfulness)
  estimated   no rating for the word: the mean of the ratings of the other English words this page
              already treats as that feeling (see WORDS in assets/js/type-a-feeling.js)

Russell (1980, A circumplex model of affect, JPSP 39, p. 1167) printed the angle on his circle for
15 of his 28 words. Where one of them is the word for a feeling here, it is kept next to the angle the
same word gets from the norms, as a check on direction (angle only: his circle has no intensity).

  python -I tools/make_feelings.py [path/to/norms.csv]
"""
import csv
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "_data" / "feelings.yml"
DEFAULT = ROOT / "tools" / "_raw" / "Warriner" / "BRM-emot-submit.csv"

CLOUD_COLS, CLOUD_ROWS = 40, 24      # the grid behind the map

# id, words rated, status
SPEC = [
    ("joy", ["joy"], "published"),
    ("sadness", ["sadness"], "published"),
    ("calm", ["calm"], "published"),
    ("fear", ["fear"], "published"),
    ("anger", ["anger"], "published"),
    ("tenderness", ["tenderness"], "published"),
    ("longing", ["homesick", "miss", "yearn"], "estimated"),
    ("wonder", ["wonder"], "published"),
    ("hope", ["hope"], "published"),
    ("nostalgia", ["nostalgia"], "published"),
    ("power", ["power"], "published"),
    ("tension", ["tension"], "published"),
    ("transcendence", ["transcendent"], "related"),
    ("playfulness", ["playful"], "related"),
    ("bittersweet", ["bittersweet"], "published"),
    ("moved", ["emotional", "tearful", "heartfelt"], "estimated"),
]
# The angles printed in the text of Russell (1980, p. 1167), for words that name one of the feelings.
RUSSELL = {"joy": ("happy", 7.8), "sadness": ("sad", 207.5), "calm": ("calm", 316.2), "tension": ("tense", 92.8)}


def load(path):
    """Every row of the norms file, and the rows by lower-case word (a few words differ only by case)."""
    rows = list(csv.DictReader(path.open(encoding="utf-8-sig", newline="")))
    return rows, {r["Word"].strip().lower(): r for r in rows}


def to_map(x):
    return (x - 5) / 4


def angle(v, a):
    return round(math.degrees(math.atan2(a, v)) % 360, 1)


def main():
    path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
    if not path.exists():
        sys.exit("Norms file not found: %s\nDownload it from the paper's supplementary material (see the top of this script)." % path)
    all_rows, norms = load(path)
    lines = [
        "# Generated by tools/make_feelings.py. Do not edit by hand; change the script and run it again.",
        "# Where each feeling sits on the map: valence (left to right) and arousal (bottom to top), -1..1.",
        "# Source: Warriner, Kuperman & Brysbaert (2013), Behavior Research Methods 45(4), 1191-1207,",
        "# doi:10.3758/s13428-012-0314-x. Ratings run 1..9; the map value is (rating - 5) / 4.",
        "feelings:",
    ]
    for fid, words, status in SPEC:
        parts = []
        for w in words:
            r = norms.get(w)
            if r is None:
                sys.exit("Not in the norms: %s (for %s)" % (w, fid))
            parts.append((w, float(r["V.Mean.Sum"]), float(r["A.Mean.Sum"]), int(r["V.Rat.Sum"])))
        rv = sum(p[1] for p in parts) / len(parts)
        ra = sum(p[2] for p in parts) / len(parts)
        v, a = round(to_map(rv), 2), round(to_map(ra), 2)
        lines += [
            "  - id: %s" % fid,
            "    v: %s" % v,
            "    a: %s" % a,
            "    status: %s" % status,
            "    rating: {valence: %.2f, arousal: %.2f}" % (rv, ra),
            "    rated:",
        ]
        for w, pv, pa, n in parts:
            lines.append('      - {word: "%s", valence: %.2f, arousal: %.2f, raters: %d}' % (w, pv, pa, n))
        if fid in RUSSELL:
            rw, rang = RUSSELL[fid]
            r = norms[rw]
            nv, na = to_map(float(r["V.Mean.Sum"])), to_map(float(r["A.Mean.Sum"]))
            lines.append('    russell: {word: "%s", angle: %.1f, norm_angle: %.1f}' % (rw, rang, angle(nv, na)))
    # The glow behind the map: how many of the rated words fall in each small square of the map.
    # Only counts are kept (no words, no single ratings).
    cloud = [[0] * CLOUD_COLS for _ in range(CLOUD_ROWS)]
    for r in all_rows:
        v, a = to_map(float(r["V.Mean.Sum"])), to_map(float(r["A.Mean.Sum"]))
        col = min(CLOUD_COLS - 1, max(0, int((v + 1) / 2 * CLOUD_COLS)))
        row = min(CLOUD_ROWS - 1, max(0, int((1 - a) / 2 * CLOUD_ROWS)))
        cloud[row][col] += 1
    total = sum(sum(row) for row in cloud)
    assert total == len(all_rows) == 13915, (total, len(all_rows))
    lines += [
        "cloud:",
        '  source: "Warriner, Kuperman & Brysbaert (2013): how many of the %d rated English words fall in each square of the map. Counts only."' % total,
        "  cols: %d" % CLOUD_COLS,
        "  rows: %d" % CLOUD_ROWS,
        "  words: %d" % total,
        "  counts:  # top row first, left to right",
    ]
    lines += ["    - [%s]" % ", ".join(str(n) for n in row) for row in cloud]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("wrote %s (%d feelings, %d words in the cloud)" % (OUT, len(SPEC), total))


if __name__ == "__main__":
    main()
